impl Project {
    /// Tracks and groups share a persisted cycle; deleting or recolouring an
    /// item does not rewind it. Older files start the cycle at the first swatch.
    pub fn take_next_colour(&mut self) -> Colour {
        let index = self.next_colour_index % LIVE_CLIP_PALETTE.len();
        self.next_colour_index = (index + 1) % LIVE_CLIP_PALETTE.len();
        LIVE_CLIP_PALETTE[index]
    }
}

impl Project {
    /// Give every unset (black) colour a palette colour, as of 2026-10-11:
    /// tracks then group tracks follow the project's colour cycle, a clip takes its
    /// track's colour, an output takes the first swatch like `Output::new`.
    /// An explicit black in a file reads the same as a missing colour.
    pub fn fill_unset_colours(&mut self) {
        for group_tracks in [false, true] {
            for index in 0..self.tracks.len() {
                if self.tracks[index].is_group() == group_tracks
                    && self.tracks[index].colour.is_unset()
                {
                    self.tracks[index].colour = self.take_next_colour();
                }
            }
        }
        for track in &mut self.tracks {
            let colour = track.colour;
            for clip in track.slots.iter_mut().filter_map(|s| s.clip.as_mut()) {
                if clip.colour.is_unset() {
                    clip.colour = colour;
                }
            }
        }
        for output in &mut self.outputs {
            if output.colour.is_unset() {
                output.colour = LIVE_CLIP_PALETTE[0];
            }
        }
    }
}
